import { isDeepStrictEqual } from "node:util";
import { invariant } from "./errors";
import { canonicalSchema, targetSchemas, type CanonicalState, type CanonicalRow, type StateDelta, type StoryAggregate, type TargetType } from "./state";
export const equal = isDeepStrictEqual;
export const rows = (state: CanonicalState, type: TargetType): CanonicalRow[] => state[type];
export function evidenceFor(a: StoryAggregate, ids: string[]) {
  invariant(new Set(ids).size === ids.length, "DUPLICATE_EVIDENCE", "Duplicate evidence reference");
  return ids.map(id => {
    const evidence = a.evidence.find(e => e.id === id);
    invariant(evidence, "EVIDENCE_NOT_FOUND", "Evidence must belong to this story");
    invariant(a.revisions.find(r => r.id === evidence.sourceRevisionId)?.visibility === "canonical", "AUTHOR_TRUTH_FORBIDDEN", "Author-only material cannot support canonical operations");
    return evidence;
  });
}
export function validateDelta(a: StoryAggregate, d: StateDelta, internalRestore = false) {
  invariant(d.sourceKind !== "restore" || internalRestore, "RESTORE_RESERVED", "Restore provenance is generated by the restore service");
  const ev = evidenceFor(a, d.evidenceIds);
  invariant(internalRestore || d.sourceKind !== "story_event" || ev.length > 0, "EVIDENCE_REQUIRED", "Story-derived proposals require anchored evidence");
  if (d.sourceKind === "story_event") {
    const event = a.events.find(e => e.id === d.sourceEventId);
    invariant(event && d.effect, "EVENT_EFFECT_REQUIRED", "Story-event deltas require an owned Event and explicit Effect");
    invariant(ev.every(e => event.evidenceIds.includes(e.id)), "EVENT_EVIDENCE_MISMATCH", "Effect evidence must be linked to its event");
  } else invariant(d.sourceEventId === null && d.effect === null, "INVALID_PROVENANCE", "Non-event changes must not impersonate event effects");
  const schema = targetSchemas[d.targetType];
  invariant(d.fieldPath === "$" || Object.hasOwn(schema.shape, d.fieldPath), "INVALID_FIELD", "Unknown typed field path");
  invariant(!["id", "active"].includes(d.fieldPath), "IDENTITY_IMMUTABLE", "Identity/lifecycle changes require whole-record governance");
  if (d.fieldPath === "$") {
    if (d.before !== null) schema.parse(d.before);
    if (d.after !== null) {
      const after = schema.parse(d.after);
      invariant(after.id === d.targetId, "IDENTITY_MISMATCH", "Target identity cannot change");
    }
  } else {
    const field = (schema.shape as Record<string, { parse(v: unknown): unknown }>)[d.fieldPath];
    field.parse(d.before); field.parse(d.after);
  }
  if (d.operation === "CREATE") invariant(d.fieldPath === "$" && d.before === null && d.after !== null && (d.after as { active: boolean }).active, "INVALID_CREATE", "CREATE requires absent before and active typed record");
  else invariant(d.before !== null || d.fieldPath !== "$", "INVALID_BEFORE", "Existing target required");
  invariant(d.after !== null || d.fieldPath !== "$", "DELETE_FORBIDDEN", "Use INVALIDATE, not deletion");
  if (d.operation === "NO_CHANGE") invariant(equal(d.before, d.after), "INVALID_NO_CHANGE", "NO_CHANGE must preserve value");
  else invariant(!equal(d.before, d.after), "NO_STATE_CHANGE", "A mutation must actually change canonical state");
  if (d.operation === "INVALIDATE") invariant(d.fieldPath === "$" && equal(d.after, { ...(d.before as object), active: false }), "INVALID_INVALIDATION", "INVALIDATE only retires the assertion");
  if (["CLOSE", "RESOLVE"].includes(d.operation)) invariant(d.targetType === "plotThreads" && (d.fieldPath === "$" ? (d.after as {status: string}).status : d.fieldPath === "status" && d.after) === "resolved", "INVALID_RESOLUTION", "CLOSE/RESOLVE must resolve a thread");
  if (d.fieldPath === "$" && !["CREATE", "INVALIDATE"].includes(d.operation) && !internalRestore)
    invariant((d.before as {active:boolean}).active === (d.after as {active:boolean}).active, "LIFECYCLE_CHANGE", "Use INVALIDATE to retire canonical records");
}
export function applyDelta(a: StoryAggregate, d: StateDelta, internalRestore = false) {
  validateDelta(a, d, internalRestore);
  invariant(d.decision === "accepted" && d.committedVersionId === null, "NOT_ACCEPTED", "Only uncommitted accepted deltas may apply", 409);
  const list = rows(a.state, d.targetType);
  const current = list.find(r => r.id === d.targetId);
  const before = d.fieldPath === "$" ? current ?? null : current ? (current as unknown as Record<string, unknown>)[d.fieldPath] : undefined;
  invariant(equal(before, d.before), "STALE_STATE", "Canonical before value has changed; review again", 409);
  if (d.operation === "NO_CHANGE") return;
  const next = targetSchemas[d.targetType].parse(d.fieldPath === "$" ? d.after : { ...current, [d.fieldPath]: d.after });
  if (d.targetType === "relationships" && "category" in next && next.category === "human_confirmed_psychological")
    invariant(internalRestore || (d.sourceKind !== "story_event" && d.basis.kinds.includes("human_confirmation")), "SOFT_INTERPRETATION", "Psychological state requires explicit human confirmation, never event inference");
  if (d.targetType === "knowledge" && "stance" in next) {
    invariant(next.stance !== "knows" || next.basis.kinds.some(k => k !== "inference"), "KNOWLEDGE_BASIS", "Inference alone is not knowledge");
    if (current && "stance" in current && current.stance === "believes" && next.believedValue !== current.believedValue && !internalRestore) {
      const correction = next.basis.correction;
      invariant(correction && correction.previousStance === current.stance && correction.previousBelievedValue === current.believedValue && correction.evidenceIds.every(id => d.evidenceIds.includes(id)), "CORRECTION_PROVENANCE", "Belief correction must preserve previous belief and correction evidence");
    }
  }
  if (d.targetType === "plotThreads" && "status" in next && next.status === "resolved" && (!current || !("status" in current) || current.status !== "resolved") && !internalRestore) {
    const support = d.resolutionSupport;
    invariant(support && support.assessment === "direct_answer" && support.coreQuestion === next.coreQuestion && support.answer === next.resolution && support.evidenceIds.every(id => d.evidenceIds.includes(id)), "INSUFFICIENT_RESOLUTION", "Resolution needs an evidence-backed answer to the exact core question");
  }
  if (current) list[list.indexOf(current)] = next;
  else list.push(next);
}
export function validateCanonical(state: CanonicalState) {
  canonicalSchema.parse(state);
  for (const list of Object.values(state)) invariant(new Set(list.map(r => r.id)).size === list.length, "DUPLICATE_ID", "Duplicate canonical identity");
  const has = (type: TargetType, id: string) => rows(state, type).some(r => r.id === id && r.active);
  const unique = (values: string[]) => invariant(new Set(values).size === values.length, "DUPLICATE_STATE", "Duplicate semantic state");
  for (const item of state.items.filter(r => r.active)) for (const field of [item.owner, item.holder])
    for (const id of [field.value, field.lastConfirmedValue]) if (id) invariant(has("characters", id), "FOREIGN_REFERENCE", "Owner/holder must reference a character in this story");
  for (const p of state.propositions.filter(r => r.active)) {
    invariant(p.kind === "reported" ? p.reporterId && p.reportedPropositionId && p.reportedPropositionId !== p.id && has("characters", p.reporterId) && has("propositions", p.reportedPropositionId) : p.reporterId === null && p.reportedPropositionId === null, "INVALID_PROPOSITION", "Reported propositions need an independent claim and reporter");
  }
  for (const w of state.worldTruth.filter(r => r.active)) invariant(has("propositions", w.propositionId), "FOREIGN_REFERENCE", "World truth proposition missing");
  for (const k of state.knowledge.filter(r => r.active)) {
    invariant(has("characters", k.characterId) && has("propositions", k.propositionId), "FOREIGN_REFERENCE", "Knowledge references must belong to this story");
    invariant(k.stance === "unaware" ? k.believedValue === null : ["knows", "believes"].includes(k.stance) ? k.believedValue !== null : true, "INVALID_BELIEVED_VALUE", "Knowledge stance/value mismatch");
  }
  for (const r of state.relationships.filter(r => r.active)) invariant(has("characters", r.fromCharacterId) && has("characters", r.toCharacterId) && r.fromCharacterId !== r.toCharacterId, "FOREIGN_REFERENCE", "Directed relationship endpoints must be distinct owned characters");
  for (const t of state.plotThreads.filter(r => r.active)) invariant(t.status === "resolved" ? t.resolution !== null : t.resolution === null, "INVALID_RESOLUTION", "Only resolved threads have a resolution");
  unique(state.worldTruth.filter(r=>r.active).map(r=>r.propositionId));
  unique(state.knowledge.filter(r=>r.active).map(r=>`${r.characterId}/${r.propositionId}`));
  unique(state.relationships.filter(r=>r.active).map(r=>`${r.fromCharacterId}/${r.toCharacterId}/${r.category}/${r.predicate}/${r.scope}`));
}
